"""Turns the raw bench CSVs into bench/results/summary.md.

    python bench/summarize.py

Reads fd-oneshot.csv and fd-server.csv (and build-times.csv, image-sizes.txt
when present) from bench/results. Nothing here is typed by hand.
"""
import csv
import statistics
from collections import defaultdict
from pathlib import Path

results = Path(__file__).resolve().parent / "results"
BUCKETS = ["small", "mid", "large", "huge"]


def load(mode):
    with open(results / f"fd-{mode}.csv", newline="") as fh:
        return list(csv.DictReader(fh))


def nums(rows, key):
    return [float(r[key]) for r in rows if r[key] != ""]


def spread(values, digits=1):
    values = sorted(values)
    return (f"{statistics.median(values):.{digits}f} "
            f"({values[0]:.{digits}f} to {values[-1]:.{digits}f})")


def main():
    runs = {m: load(m) for m in ("oneshot", "server")}
    out = []
    out.append("# Results summary\n")
    out.append("Generated by bench/summarize.py from the CSV files in this folder.")
    out.append("Cells are median (min to max) over all runs in the group.\n")

    per_commit = {}
    for r in runs["oneshot"]:
        per_commit.setdefault(r["commit"], r)
    out.append("## Commits\n")
    out.append("| commit | bucket | filtered diff bytes | prompt bytes | prompt tokens | generated tokens | truncated |")
    out.append("|---|---|---|---|---|---|---|")
    for sha, r in per_commit.items():
        out.append(f"| {sha[:10]} | {r['bucket']} | {r['diff_bytes']} | {r['prompt_bytes']} | "
                   f"{r['prompt_tokens']} | {spread(nums([x for x in runs['oneshot'] if x['commit'] == sha], 'completion_tokens'), 0)} | {r['truncated']} |")

    out.append("\n## Seconds per summary by diff size\n")
    out.append("Wall time is measured around the whole `diffsum` call, container start included. "
               "Tool time is what summarize.sh reports inside the container.\n")
    out.append("| bucket | commits | one-shot wall s | server wall s | server saves s (median) | one-shot tool s | server tool s |")
    out.append("|---|---|---|---|---|---|---|")
    for b in BUCKETS:
        o = [r for r in runs["oneshot"] if r["bucket"] == b]
        s = [r for r in runs["server"] if r["bucket"] == b]
        if not o or not s:
            continue
        saves = statistics.median(nums(o, "wall_s")) - statistics.median(nums(s, "wall_s"))
        out.append(f"| {b} | {len({r['commit'] for r in o})} | {spread(nums(o, 'wall_s'))} | "
                   f"{spread(nums(s, 'wall_s'))} | {saves:.1f} | {spread(nums(o, 'tool_s'))} | {spread(nums(s, 'tool_s'))} |")

    out.append("\n## Model load (one-shot)\n")
    out.append(f"load seconds, all {len(runs['oneshot'])} runs: {spread(nums(runs['oneshot'], 'load_s'), 2)}\n")

    out.append("## Throughput\n")
    out.append("| mode | prompt eval tokens/s | generation tokens/s |")
    out.append("|---|---|---|")
    for m, rows in runs.items():
        out.append(f"| {m} | {spread(nums(rows, 'prompt_tok_per_s'))} | {spread(nums(rows, 'gen_tok_per_s'))} |")
    out.append("\nPrompt evaluation tokens/s by bucket (both modes together):\n")
    out.append("| bucket | prompt tokens/s | time to first token s (approx.) |")
    out.append("|---|---|---|")
    for b in BUCKETS:
        rows = [r for m in runs.values() for r in m if r["bucket"] == b]
        if rows:
            out.append(f"| {b} | {spread(nums(rows, 'prompt_tok_per_s'))} | {spread(nums(rows, 'ttft_s'), 2)} |")
    out.append("\nTime to first token is not reported by the server. The figure above is prompt "
               "evaluation time plus the average time of one generated token.")

    out.append("\n## Memory\n")
    out.append("peak RSS is the high-water mark of the model process (VmHWM). In server mode it is "
               "the server container's process over its whole life, so it covers the largest prompt seen so far.\n")
    out.append("| mode | peak RSS MiB | cgroup memory.peak MiB |")
    out.append("|---|---|---|")
    for m, rows in runs.items():
        rss = [v / 2**20 for v in nums(rows, "peak_rss_bytes")]
        cg = [v / 2**20 for v in nums(rows, "cgroup_peak_bytes")]
        out.append(f"| {m} | {spread(rss, 0)} | {spread(cg, 0)} |")

    out.append("\n## Determinism\n")
    for m, rows in runs.items():
        same = sum(1 for r in rows if r["same_as_first"] == "yes")
        by = defaultdict(list)
        for r in rows:
            by[r["commit"]].append(r["same_as_first"] == "yes")
        full = sum(1 for v in by.values() if all(v))
        out.append(f"- {m}: {same} of {len(rows)} outputs match the first run of their commit byte for byte; "
                   f"{full} of {len(by)} commits matched on every repetition.")
    first = {m: {} for m in runs}
    for m, rows in runs.items():
        for r in rows:
            first[m].setdefault(r["commit"], r["summary_sha256"])
    agree = sum(1 for c in first["oneshot"] if first["server"].get(c) == first["oneshot"][c])
    out.append(f"- one-shot and server mode produced the same text for {agree} of {len(first['oneshot'])} commits.")

    for name, title in (("build-times.csv", "Cold build of the tool image"), ("image-sizes.txt", "Image sizes")):
        path = results / name
        if path.exists():
            out.append(f"\n## {title}\n")
            out.append("```")
            out.append(path.read_text().rstrip())
            out.append("```")

    (results / "summary.md").write_text("\n".join(out) + "\n")
    print("wrote", results / "summary.md")


main()
